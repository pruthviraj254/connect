/**
 * 1. Copies pdfjs worker into Next static output + public (for URL-based loading).
 * 2. Generates an inline TypeScript module with the worker source as base64
 *    so it can be embedded in the JS bundle — no fetch/URL needed at runtime.
 */
const fs = require('node:fs');
const path = require('node:path');

const desktopRoot = path.join(__dirname, '..');

function resolveWorkerSrc() {
  const candidates = [
    path.join(desktopRoot, 'node_modules', 'pdfjs-dist', 'build', 'pdf.worker.min.mjs'),
  ];
  try {
    candidates.unshift(
      path.join(path.dirname(require.resolve('pdfjs-dist/package.json')), 'build', 'pdf.worker.min.mjs'),
    );
  } catch {
    /* not installed */
  }
  return candidates.find((p) => fs.existsSync(p)) ?? null;
}

const workerSrc = resolveWorkerSrc();

if (!workerSrc) {
  console.warn('[copy-pdf-worker] pdfjs-dist worker not found — run pnpm install');
  process.exit(0);
}

const targets = [
  path.join(desktopRoot, 'src', 'renderer', 'public', 'pdf.worker.min.mjs'),
  path.join(desktopRoot, 'src', 'renderer', 'out', 'pdf.worker.min.mjs'),
];

for (const dest of targets) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(workerSrc, dest);
  console.log('[copy-pdf-worker] copied to', dest);
}

const workerContent = fs.readFileSync(workerSrc, 'utf8');
const b64 = Buffer.from(workerContent, 'utf8').toString('base64');
const inlineModule = `// AUTO-GENERATED by scripts/copy-pdf-worker.cjs — do not edit\nexport const PDFJS_WORKER_BASE64 = "${b64}";\n`;
const inlineDest = path.join(desktopRoot, 'src', 'renderer', 'lib', 'pdfjs-worker-inline.ts');
fs.mkdirSync(path.dirname(inlineDest), { recursive: true });
fs.writeFileSync(inlineDest, inlineModule);
console.log('[copy-pdf-worker] generated inline worker module', inlineDest);
